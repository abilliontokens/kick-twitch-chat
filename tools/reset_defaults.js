import { connect, openTab } from "./cdp.js";
const extId = process.argv[2];
const t = await openTab(`chrome-extension://${extId}/popup/popup.html`);
await new Promise(r => setTimeout(r, 500));
const c = await connect(t.webSocketDebuggerUrl);
await c.send("Runtime.enable");
const defaults = { enabled: true, twitchChannel: {}, kickByTwitch: {}, showTimestamps: true, showBadges: true, tintTwitch: true, tintKick: true, colorBar: true, kickIcon: true, kickBadges: true };
const r = await c.send("Runtime.evaluate", { expression: `chrome.storage.sync.set(${JSON.stringify(defaults)}).then(() => chrome.storage.sync.get(null))`, awaitPromise: true, returnByValue: true });
console.log(JSON.stringify(r.result.value));
c.close(); await fetch(`http://127.0.0.1:9333/json/close/${t.id}`);
